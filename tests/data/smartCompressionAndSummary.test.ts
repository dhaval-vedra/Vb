import { describe, it, expect } from 'vitest';
import { SmartDataCompressor } from '../../src/js/core/smartDataCompressor.ts';
import { SmartSummaryEngine, SummaryConfig } from '../../src/js/core/smartSummaryEngine.ts';

describe('SmartDataCompressor & SmartSummaryEngine', () => {
    const mockDataset = [
        { id: 1, region: 'North', category: 'Electronics', sales: 1200, cost: 800, date: '2025-01-15' },
        { id: 2, region: 'South', category: 'Clothing', sales: 450, cost: 200, date: '2025-01-16' },
        { id: 3, region: 'North', category: 'Electronics', sales: 1500, cost: 950, date: '2025-02-10' },
        { id: 4, region: 'East', category: 'Clothing', sales: 600, cost: 310, date: '2025-02-20' },
        { id: 5, region: 'North', category: 'Home', sales: 300, cost: 150, date: '2025-03-05' },
        { id: 6, region: 'South', category: 'Clothing', sales: 700, cost: 350, date: '2025-03-12' },
        { id: 7, region: 'North', category: 'Electronics', sales: 2100, cost: 1300, date: '2025-04-01' }
    ];
    const headers = ['id', 'region', 'category', 'sales', 'cost', 'date'];

    describe('SmartDataCompressor', () => {
        it('should compress tabular data into columnar/dictionary format', async () => {
            const payload = await SmartDataCompressor.compressDataset(mockDataset, headers);

            expect(payload).toBeDefined();
            expect(payload.rowCount).toBe(mockDataset.length);
            expect(payload.headers).toEqual(headers);
            expect(payload.compressedData).toBeTypeOf('string');
            expect(payload.stats.originalSizeBytes).toBeGreaterThan(0);
            expect(payload.stats.compressedSizeBytes).toBeGreaterThan(0);
        });

        it('should accurately decompress compressed data back to original rows', async () => {
            const payload = await SmartDataCompressor.compressDataset(mockDataset, headers);
            const decompressed = await SmartDataCompressor.decompressDataset(payload);

            expect(decompressed.length).toBe(mockDataset.length);
            expect(decompressed[0].region).toBe('North');
            expect(decompressed[0].category).toBe('Electronics');
            expect(Number(decompressed[0].sales)).toBe(1200);
        });
    });

    describe('SmartSummaryEngine', () => {
        it('should profile columns accurately', () => {
            const profiles = SmartSummaryEngine.profileColumns(mockDataset, headers);
            expect(profiles.length).toBe(headers.length);

            const salesProfile = profiles.find(p => p.name === 'sales');
            expect(salesProfile?.type).toBe('numeric');
            expect(salesProfile?.isRecommendedMetric).toBe(true);

            const regionProfile = profiles.find(p => p.name === 'region');
            expect(regionProfile?.type).toBe('categorical');
            expect(regionProfile?.isRecommendedDimension).toBe(true);
        });

        it('should auto-generate an optimal default SummaryConfig', () => {
            const config = SmartSummaryEngine.generateSmartDefaultConfig(mockDataset, headers);
            expect(config).toBeDefined();
            expect(config.dimensions.length).toBeGreaterThan(0);
            expect(config.metrics.length).toBeGreaterThan(0);
        });

        it('should aggregate dataset correctly based on specified dimensions and metrics', () => {
            const config: SummaryConfig = {
                enabled: true,
                dimensions: ['region'],
                metrics: [
                    { column: 'sales', agg: 'sum' },
                    { column: 'cost', agg: 'avg' }
                ],
                thresholdRows: 1,
                autoGenerated: false
            };

            const result = SmartSummaryEngine.computeSummary(mockDataset, config);

            expect(result).toBeDefined();
            expect(result.rawRowCount).toBe(7);
            // Regions are North (4 rows), South (2 rows), East (1 row) -> 3 summary rows
            expect(result.summaryRowCount).toBe(3);
            expect(result.reductionPercentage).toBeGreaterThan(0);

            const northSummary = result.summaryData.find(r => r.region === 'North');
            expect(northSummary).toBeDefined();
            // North sales: 1200 + 1500 + 300 + 2100 = 5100
            expect(northSummary?.sales).toBe(5100);
            // North cost avg: (800 + 950 + 150 + 1300) / 4 = 800
            expect(northSummary?.cost).toBe(800);
            expect(northSummary?._record_count).toBe(4);
        });
    });
});
