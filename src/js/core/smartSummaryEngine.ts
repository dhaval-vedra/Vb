    /**
     * Persist Summary Configuration to Storage
     */
    public static async saveSummaryConfig(userId: string, config: SummaryConfig): Promise<boolean> {
        try {
            const key = `summary_config_${userId || 'guest'}`;
            await vedraStorage.setItem(STORES.METADATA, key, config);
            this.setActiveConfig(config);
            return true;
        } catch (err) {
            console.error('[SmartSummaryEngine] Error saving config:', err);
            return false;
        }
    }

    /**
     * Load Summary Configuration from Storage
     */
    public static async loadSummaryConfig(userId: string): Promise<SummaryConfig | null> {
        try {
            const key = `summary_config_${userId || 'guest'}`;
            const config = await vedraStorage.getItem<SummaryConfig>(STORES.METADATA, key);
            if (config) {
                this.setActiveConfig(config);
            }
            return config;
        } catch (err) {
            console.error('[SmartSummaryEngine] Error loading config:', err);
            return null;
        }
    }

